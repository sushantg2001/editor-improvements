import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// Optional: build straight into a vault so `bun run dev` is a live loop.
//   OBSIDIAN_PLUGIN_DIR="/path/to/vault/.obsidian/plugins/vim-tools" bun run dev
const pluginDir = process.env.OBSIDIAN_PLUGIN_DIR;
const outfile = pluginDir ? join(pluginDir, 'main.js') : 'main.js';

if (pluginDir) {
	mkdirSync(pluginDir, { recursive: true });
}

/** Keeps manifest.json and styles.css next to main.js when deploying into a vault. */
const copyAssets = {
	name: 'copy-assets',
	setup(build) {
		build.onEnd(() => {
			if (!pluginDir) {
				return;
			}
			for (const asset of ['manifest.json', 'styles.css']) {
				copyFileSync(asset, join(pluginDir, asset));
			}
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile,
	minify: prod,
	plugins: [copyAssets],
});

mkdirSync(dirname(outfile), { recursive: true });

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}

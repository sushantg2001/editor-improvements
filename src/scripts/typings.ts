/**
 * The ambient declaration written into the scripts folder so editors
 * autocomplete the `vim` object.
 *
 * Kept as a literal rather than generated from the source types: scripts are
 * plain `.js` with no build step, so what they need is one self-contained
 * `.d.ts` next to them, not a reference into the plugin's compiled output.
 */
export const TYPINGS_FILENAME = "vim-tools.d.ts";

export const TYPINGS = `// Generated by Vim Tools. Do not edit — it is rewritten on every reload.
// Scripts in this folder are executed by the Vim Tools plugin. See SECURITY.md.

declare global {
	/** Vim mapping contexts, spelled as CodeMirror's vim addon names them. */
	type BindingContext = "normal" | "visual" | "insert" | "operatorPending";

	interface EditorPosition {
		line: number;
		ch: number;
	}

	interface VimActionArgs {
		/** Count typed before the key, e.g. 3 for \`3gz\`. Defaults to 1. */
		repeat: number;
		register?: string;
		/** Present for operators: the range the operator was invoked over. */
		range?: { from: EditorPosition; to: EditorPosition };
		/**
		 * Present for motions: where the motion starts from. Return the position
		 * to go to; the same function then serves a key, an operator and the
		 * command palette.
		 */
		head?: EditorPosition;
	}

	interface VimContext {
		/** The Obsidian app. */
		app: any;
		/** Obsidian's Editor for the active note. */
		editor: any;
		/** The CodeMirror 6 EditorView. */
		view: any;
		/** CodeMirror 5 shim, as the Vim API expects. */
		cm: any;
		mode:
			| "normal"
			| "insert"
			| "visual"
			| "visual-line"
			| "visual-block"
			| "replace";
	}

	type ScriptRun = (ctx: VimContext, args: VimActionArgs) => unknown;

	interface DefineOptions {
		/** Shown in the command palette. Defaults to the id. */
		name?: string;
		group?: string;
		/**
		 * Register an Obsidian command, and so a hotkey slot. Default true,
		 * except for operators, which need a motion and default to false.
		 */
		command?: boolean;
		/** Set false for actions that work without an open note. */
		needsEditor?: boolean;
		/** Mode to leave the editor in once the action completes. */
		resultMode?: "insert" | "normal";
		/** The action changes the document, so the . key repeats it. */
		isEdit?: boolean;
	}

	interface VimToolsApi {
		readonly app: any;

		/** Defines an action: runs, changes nothing about the cursor by itself. */
		action(id: string, run: ScriptRun, options?: DefineOptions): void;
		/** Defines a motion. Return an { line, ch } position. Composes with d/y/c. */
		motion(id: string, run: ScriptRun, options?: DefineOptions): void;
		/** Defines an operator. Receives args.range. */
		operator(id: string, run: ScriptRun, options?: DefineOptions): void;

		/** Recursive maps, as in vim's nmap family. */
		map(keys: string, rhs: string, contexts?: BindingContext[]): void;
		nmap(keys: string, rhs: string): void;
		vmap(keys: string, rhs: string): void;
		imap(keys: string, rhs: string): void;
		omap(keys: string, rhs: string): void;

		/** Non-recursive maps, as in vim's nnoremap family. */
		noremap(keys: string, rhs: string, contexts?: BindingContext[]): void;
		nnoremap(keys: string, rhs: string): void;
		vnoremap(keys: string, rhs: string): void;
		inoremap(keys: string, rhs: string): void;
		onoremap(keys: string, rhs: string): void;

		/**
		 * Removes vim's built-in binding, so a key like S or , can start a longer
		 * mapping. Lasts until Obsidian restarts; it is not undone by editing
		 * the script.
		 */
		unmap(keys: string, contexts?: BindingContext[]): void;
		nunmap(keys: string): void;
		vunmap(keys: string): void;
		iunmap(keys: string): void;
		ounmap(keys: string): void;

		/** Binds a key straight to an action id, with no id-vs-keys guessing. */
		bind(keys: string, actionId: string, contexts?: BindingContext[]): void;

		/** Sets what <leader> expands to for every mapping after this call. */
		leader(key: string): void;

		/** Sets a vim option, e.g. set("textwidth", 80). */
		set(option: string, value: unknown): void;

		/** Runs an Obsidian command by id. Throws if there is no such command. */
		obcommand(id: string): boolean;

		notice(message: string, timeout?: number): void;
	}

	const vim: VimToolsApi;
}

export {};
`;
